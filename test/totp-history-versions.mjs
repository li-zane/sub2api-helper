import assert from "node:assert/strict";
import fs from "node:fs/promises";
import path from "node:path";
import os from "node:os";
import { compactTotpHistory } from "../src/totp-history-versions.mjs";
import { recordCredentialHistory, readCredentialHistory, readAccountLog } from "../src/account-history.mjs";
import { readAccountLogEntries } from "../src/account-log-entries.mjs";
const root = await fs.mkdtemp(path.join(os.tmpdir(), "helper-totp-versions-"));
const job = { outputPath: path.join(root, "oauth.json"), email: "fixture@example.test", totpSecret: "JBSWY3DPEHPK3PXP", createdAt: "2026-10-01T00:00:00Z", securityState: { totpEnabled: null }, logs: "" };
const keyA = "GEZDGNBVGY3TQOJQ", keyB = job.totpSecret, keyC = "KRSXG5DSNFXGOIDB";
const event = (stage, before, after, n) => recordCredentialHistory(root, { type: "2fa", stage, before, after, at: `2026-11-10T00:00:${String(n).padStart(2, "0")}Z` });
try {
  await event("imported", null, { totpSecret: keyA }, 1);
  await event("started", { totpSecret: keyA }, null, 2);
  await event("disabling", { totpSecret: keyA }, { operation: "replace_totp", remote_disabled: false }, 3);
  await event("disabled", { totpSecret: keyA }, { remote_disabled: true }, 4);
  await event("activation_pending", { totpSecret: keyA }, { secret: keyB }, 5);
  await event("activated", { totpSecret: keyA }, { secret: keyB, activation_succeeded: true }, 6);
  const confirmed = await event("confirmed", { totpSecret: keyA }, { secret: keyB, activation_succeeded: true, confirmation_succeeded: true }, 7);
  await event("activated_before_save", { totpSecret: keyA }, { totpSecret: keyB, activation_succeeded: true }, 8);
  await event("activation_failed", { totpSecret: keyB }, { secret: keyC, activation_succeeded: false, activation_error: "fixture rejected" }, 9);
  const before = await readCredentialHistory(root), copy = JSON.stringify(before);
  const compact = compactTotpHistory([...before, { id: "current-2fa", type: "2fa", stage: "current", at: job.createdAt, after: { totpSecret: keyB, localRecord: true, remoteEnabled: null } }]);
  assert.equal(compact.length, 3, "nine stages plus local alias should become three unique keys");
  assert.equal(JSON.stringify(before), copy, "projection mutated original records");
  const current = compact.find(e => e.id === "current-2fa"); assert.equal(current.at, "2026-11-10T00:00:08Z");
  assert.equal(current.after.totpSecret, keyB); assert.equal(current.after.remoteEnabled, null);
  assert.equal(compact.find(e => e.after.totpSecret === keyC).stage, "candidate_failed");
  const list = await readAccountLogEntries(job, { view: "credentials" }); assert.equal(list.entries.length, 3);
  for (const key of [keyA, keyB, keyC]) assert(!JSON.stringify(list.entries).includes(key));
  assert((await readAccountLogEntries(job, { view: "credentials", entryId: confirmed.id })).content.includes(keyB), "raw recovery IDs must still resolve");
  job.totpSecret = "";
  await event("local_key_delete_prepared", { totpSecret: keyB }, { totpSecret: "" }, 10);
  const cleared = await readAccountLogEntries(job, { view: "credentials" });
  assert.equal(cleared.entries.filter(e => e.type === "2fa").length, 4);
  assert(cleared.entries.some(e => e.stage === "cleared")); assert(!cleared.entries.some(e => e.id === "current-2fa"));
  const dump = (await readAccountLog(job, { full: true, credentials: true })).logs;
  for (const key of [keyA, keyB, keyC]) assert(dump.includes(key), "recovery values were lost");
  assert.equal((await readCredentialHistory(root)).length, 10);
  console.log("TOTP_VERSIONS_PASS duplicate stages collapse by key; current/confirmed/candidate/clear distinguished; true version time; lazy secrets/raw IDs and all original recovery records preserved");
} finally { await fs.rm(root, { recursive: true, force: true }); }
