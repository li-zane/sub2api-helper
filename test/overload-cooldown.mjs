import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { OverloadCooldown, normalizeOverloadCooldown } from "../src/overload-cooldown.mjs";
import { collectOverloadWindow, OVERLOAD_MESSAGE } from "../src/overload-monitor.mjs";

const temp = await fs.mkdtemp(path.join(os.tmpdir(), "tosub2-overload-cooldown-"));
let now = Date.parse("2026-11-01T04:00:00Z");
let config = { baseUrl: "https://pool-a.fixture", adminApiKey: "fixture" };
let settings = { windowMinutes: 15, threshold: 3, cooldownMinutes: 30 };
const email = "auto@example.test";
let records = [{ id: "7", enabled: true }, { id: "8", enabled: false }, { id: "9", enabled: true }];
let rows = [];
let failPause = false;
let failResume = false;
let listIncomplete = false;
let logFailure = false;
const mutations = [];
let lastDelay;
const filePath = path.join(temp, "cooldown.json");
const row = (id, time, fields = {}) => ({ id, account_id: 7, status_code: 503, message: OVERLOAD_MESSAGE, created_at: new Date(time).toISOString(), ...fields });
const options = {
  filePath, getConfig: () => config, backendIdentity: c => c?.baseUrl, getSettings: () => settings,
  now: () => now, setTimer: (_callback, delay) => { lastDelay = delay; return { unref() {} }; }, clearTimer: () => {},
  listAccounts: async () => { if (listIncomplete) throw new Error("incomplete list"); return new Map([[email, records.map(record => ({ ...record }))]]); },
  request: async (_config, endpoint, requestOptions) => {
    const match = /accounts\/(\d+)\/schedulable/.exec(endpoint);
    if (match) {
      const enabled = JSON.parse(requestOptions.body).schedulable;
      const disk = JSON.parse(await fs.readFile(filePath, "utf8"));
      assert(disk.accounts[email].resumeAccountIds.includes(match[1]), "restore intent is durable before remote changes");
      if ((!enabled && failPause && match[1] === "9") || (enabled && failResume)) throw new Error(enabled ? "resume unavailable" : "pause unavailable");
      mutations.push({ id: match[1], enabled });
      const record = records.find(record => record.id === match[1]);
      if (record) record.enabled = enabled;
      return {};
    }
    if (logFailure) throw new Error("logs unavailable");
    const url = new URL(endpoint, "https://fixture");
    const accountId = url.searchParams.get("account_id");
    const matching = rows.filter(row => String(row.account_id) === accountId);
    return { data: { total: matching.length, items: matching } };
  },
};
let service = new OverloadCooldown(options);
const run = async () => { service.stopped = false; service.rerun = true; do { await service.refresh(); } while (service.running); };
try {
  assert.deepEqual(normalizeOverloadCooldown(), { windowMinutes: 15, threshold: 10, cooldownMinutes: 60 });
  for (const rule of [{ windowMinutes: 0 }, { threshold: true }, { threshold: "" }, { cooldownMinutes: 43201 }, []]) assert.throws(() => normalizeOverloadCooldown(rule));
  rows = [row(1, now - 15 * 60_000), row(2, now - 1), row(3, now - 500), row(3, now - 500), row(4, now), row(5, now - 15 * 60_000 - 1), row(6, now - 3, { status_code: 502 })];
  const count = await collectOverloadWindow({ start: now - 15 * 60_000, end: now, config, accountIds: [7], request: options.request });
  assert.equal(count, 3, "rolling interval is half-open and duplicate attempts count once");
  await run(); assert.equal(mutations.length, 0, "disabled by default");
  service.stopped = true; await service.setEnabled(email, true);
  failPause = true;
  await run();
  assert.equal(records[0].enabled, false);
  assert.equal(records[2].enabled, true);
  assert.equal(service.snapshot(email).phase, "pausing");
  assert.match(service.snapshot(email).lastError, /pause unavailable/);
  assert.equal(service.snapshot(email).windowCount, 3);
  assert.equal(service.snapshot(email).coolingUntil, new Date(now + 30 * 60_000).toISOString());
  assert.equal(lastDelay, 60_000, "minute polling is separate from hourly chart scheduling");
  await service.stop();
  service = new OverloadCooldown(options); await service.load();
  assert.equal(service.snapshot(email).enabled, true, "switch survives restart");
  failPause = false;
  await run();
  assert.equal(service.snapshot(email).phase, "cooling");
  assert.equal(records[2].enabled, false, "partial pause retries after restart");
  assert(mutations.every(change => change.id !== "8"), "originally disabled rows are never owned");
  records[0].enabled = true; await run();
  assert.equal(records[0].enabled, false, "pause is reasserted if background repair enables a cooling account");
  now += 30 * 60_000 - 250;
  await run(); assert.equal(lastDelay, 250, "wake at exact cooldown expiry");
  now += 250; failResume = true;
  await run();
  assert.equal(service.snapshot(email).phase, "resuming");
  assert(service.isPaused(email));
  assert.match(service.snapshot(email).lastError, /resume unavailable/);
  failResume = false; await run();
  assert.equal(service.snapshot(email).phase, "idle");
  assert.equal(records[0].enabled, true);
  assert.equal(records[2].enabled, true);
  assert.equal(records[1].enabled, false);
  const countAfterResume = mutations.length;
  await run();
  assert.equal(mutations.length, countAfterResume, "pre-cooldown logs are excluded after resume");
  now += 60_000;
  rows = [row(10, now - 100), row(11, now - 90), row(12, now - 80)];
  await run(); assert(service.isPaused(email));
  const countBeforeBackend = mutations.length;
  config = { baseUrl: "https://pool-b.fixture", adminApiKey: "fixture" };
  assert.equal(service.isPaused(email), false, "old-backend pause cannot disable new-backend uploads");
  await service.manualOverride(email, ["7", "9"], async () => {});
  assert(service.accounts.get(email).resumeAccountIds.length, "manual change on another backend preserves original restore intent");
  now += 31 * 60_000; await run();
  assert.equal(mutations.length, countBeforeBackend, "saved row IDs are never applied to another backend");
  assert.match(service.snapshot(email).lastError, /后端已变化/);
  config = { baseUrl: "https://pool-a.fixture", adminApiKey: "fixture" }; await run();
  now += 60_000;
  rows = [row(20, now - 100), row(21, now - 90), row(22, now - 80)];
  await run(); assert(service.isPaused(email));
  await service.manualOverride(email, ["7", "9"], async () => { records[0].enabled = false; records[2].enabled = false; });
  now += 31 * 60_000; await run();
  assert.equal(records[0].enabled, false, "manual disable takes precedence over automatic restore");
  assert.equal(service.isPaused(email), false);
  records[0].enabled = true;
  now += 60_000; rows = [row(30, now - 100), row(31, now - 90), row(32, now - 80)];
  await run(); assert(service.isPaused(email));
  await service.setEnabled(email, false); await service.refresh();
  assert.equal(service.snapshot(email).enabled, false);
  assert.equal(service.snapshot(email).phase, "idle", "switch-off resumes owned accounts");
  assert.equal(records[0].enabled, true);
  await service.setEnabled(email, true);
  listIncomplete = true; const initial = mutations.length; await run();
  assert.equal(mutations.length, initial); assert.match(service.snapshot(email).lastError, /incomplete/);
  listIncomplete = false; logFailure = true; now += 60_000; await run();
  assert.equal(mutations.length, initial); assert.match(service.snapshot(email).lastError, /logs unavailable/);
  await service.stop();
  const originalPersist = service.persist.bind(service);
  let failWrite = true;
  service.persist = () => { if (failWrite) { failWrite = false; return Promise.reject(new Error("disk unavailable")); } return originalPersist(); };
  const writes = await Promise.allSettled([service.setEnabled("failed@example.test", true), service.setEnabled("saved@example.test", true)]);
  assert.equal(writes[0].status, "rejected");
  assert.equal(writes[1].status, "fulfilled");
  const disk = JSON.parse(await fs.readFile(filePath, "utf8"));
  assert.equal(disk.accounts["failed@example.test"], undefined, "concurrent save cannot resurrect a failed switch write");
  assert.equal(disk.accounts["saved@example.test"].enabled, true);
  console.log("PASS: rolling-window boundaries/deduplication, exact threshold pause, durable intent/partial retry, restart/expiry restore, minute scheduling, fresh counting, manual-disable precedence, switch-off restore, backend isolation and missing-data preservation");
} finally { await service.stop(); await fs.rm(temp, { recursive: true, force: true }); }
